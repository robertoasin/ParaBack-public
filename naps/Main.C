static void SIGALRM_handler(int signum) {
  const char msg[] = "\n[naps] 10 seconds timeout during signal handling. Force killing.\n";
  write(2, msg, sizeof(msg) - 1);
  _exit(1);
}

static void SIGTERM_handler(int signum) {
  static volatile sig_atomic_t handling = 0;
  if (__sync_lock_test_and_set(&handling, 1)) {
    while(1) pause(); // Prevent re-entry or concurrent execution
  }

  // Handle immediate termination with 10s deadline
  signal(SIGALRM, SIGALRM_handler);
  alarm(10);

  bool normalExit = (signum == SIGUSR1);
  if (!normalExit) {
      const char msg[] = "\n*** TERMINATED *** by signal\n";
      write(1, msg, sizeof(msg) - 1);
  }

  if (pb_solver) {
      pb_solver->outputResult(pb_solver->get_pb_solver_status(), config, normalExit);
      _exit(pb_solver->get_best_goalvalue() == Int_MAX ? 0 : 10);
  } else {
      _exit(10);
  }
}

